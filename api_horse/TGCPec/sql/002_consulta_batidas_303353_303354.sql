SELECT TRIM(RF.RDB$FIELD_NAME) AS COLUNA
FROM RDB$RELATION_FIELDS RF
WHERE RF.RDB$RELATION_NAME = 'CAD_BATIDA'
  AND TRIM(RF.RDB$FIELD_NAME) STARTING WITH 'CBT_'
ORDER BY RF.RDB$FIELD_POSITION;

SELECT
  CBT_CODIGO,
  CBT_CODRACAOPROD,
  CBT_QTDEBATIDA,
  CBT_QTDEPREVISTA,
  CBT_CUSTO,
  CBT_DATA,
  CBT_INICIO,
  CBT_FIM,
  CBT_LOTE_FABRICACAO,
  CBT_COD_OPERADOR_PA,
  CBT_NOMEOPERADOR,
  CBT_NOME_MOTORISTA
FROM CAD_BATIDA
WHERE CBT_CODIGO IN (303353, 303354)
ORDER BY CBT_CODIGO;

SELECT
  DBT_CODBATIDA,
  DBT_CODALIMENTO,
  DBT_QTDE,
  DBT_QTDEPREVISTA,
  DBT_CUSTO,
  DBT_DATA,
  DBT_HORA_INI,
  DBT_HORA_FIM
FROM DET_BATIDA
WHERE DBT_CODBATIDA IN (303353, 303354)
ORDER BY DBT_CODBATIDA, DBT_CODALIMENTO, DBT_CODIGO;
